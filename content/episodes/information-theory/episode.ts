import React from 'react';
import {z} from 'zod';
import type {EpisodeModule} from '../../episode-module';
import {episodeManifestSchema, sceneSchema} from '../../schema';
import {manifest} from './manifest';
import {InformationScene} from './scenes/InformationScene';
const visualIds = ['possibility','surprise','entropy','logarithm','bits','compression','source-code','channel','capacity','mutual','inference','ending'] as const;
const localVisualSchema = z.enum(visualIds);
const localManifestSchema = episodeManifestSchema.safeExtend({scenes: z.array(sceneSchema.safeExtend({visual: localVisualSchema}))});
const validatedManifest = localManifestSchema.parse(manifest);
export const episode: EpisodeModule = {manifest: validatedManifest, renderScene: ({scene, frame}) => React.createElement(InformationScene, {visual: scene.visual, frame})};
