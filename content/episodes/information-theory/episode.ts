import React from 'react';
import {z} from 'zod';
import type {EpisodeModule} from '../../episode-module';
import {episodeManifestSchema, sceneSchema} from '../../schema';
import {manifest} from './manifest';
import {InformationScene} from './scenes/InformationScene';
const localVisualSchema=z.enum(['uncertainty','one-bit','log-n']);
type LocalVisual = z.infer<typeof localVisualSchema>;
const localManifestSchema=episodeManifestSchema.safeExtend({scenes:z.array(sceneSchema.safeExtend({visual:localVisualSchema}))});
const validatedManifest=localManifestSchema.parse(manifest);
export const episode: EpisodeModule={manifest:validatedManifest,renderScene:({scene})=>React.createElement(InformationScene,{visual:scene.visual as LocalVisual})};
